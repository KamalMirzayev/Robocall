build_apps() {
  log "Installing dependencies and building applications"

  echo "  - robocall-frontend"
  (cd "$PROJECT_ROOT/apps/frontend" \
    && sudo -u "$SERVICE_USER" -H npm install \
    && sudo -u "$SERVICE_USER" -H npm run build)

  echo "  - callbot backend"
  (cd "$PROJECT_ROOT/apps/callbot-backend" \
    && sudo -u "$SERVICE_USER" -H npm install \
    && sudo -u "$SERVICE_USER" -H npm run build \
    && sudo -u "$SERVICE_USER" -H npm run db:push)

  echo "  - robocall-telephony backend (apps/telephony)"
  (cd "$PROJECT_ROOT/apps/telephony" \
    && sudo -u "$SERVICE_USER" -H npm install)

  ok "Dependencies installed and apps built"
}

install_systemd_services() {
  log "Installing systemd services"
  cp "$PROJECT_ROOT/infra/systemd/robocall-api.service" /etc/systemd/system/
  cp "$PROJECT_ROOT/infra/systemd/robocall-frontend.service" /etc/systemd/system/
  cp "$PROJECT_ROOT/infra/systemd/robocall-telephony.service" /etc/systemd/system/
  systemctl daemon-reload
  systemctl enable --now robocall-api robocall-frontend robocall-telephony
  ok "robocall-api, robocall-frontend, robocall-telephony enabled and started"
}

configure_ufw() {
  log "Configuring firewall (ufw)"
  ufw allow OpenSSH
  ufw allow 80/tcp
  ufw allow 443/tcp

  if [ -n "$ASTERISK_TRUNK_PROVIDER_IP" ]; then
    ufw allow from "$ASTERISK_TRUNK_PROVIDER_IP" to any port 5060 proto udp
    ufw allow from "$ASTERISK_TRUNK_PROVIDER_IP" to any port 11000:11100 proto udp
    ok "Opened SIP (5060/udp) + RTP (11000-11100/udp) to trunk provider ${ASTERISK_TRUNK_PROVIDER_IP}"
  else
    echo "  SIP/RTP left closed — no ASTERISK_TRUNK_PROVIDER_IP set. Once you know your"
    echo "  trunk/gateway's IP, run:"
    echo "    sudo ufw allow from <TRUNK_IP> to any port 5060 proto udp"
    echo "    sudo ufw allow from <TRUNK_IP> to any port 11000:11100 proto udp"
  fi

  ufw --force enable
  ok "ufw enabled: 22, 80, 443 open; app ports 3001/4000/8090/5039/8088 stay loopback-only"
}

configure_nginx() {
  log "Configuring nginx for ${DOMAIN}"
  # The tracked template uses __FRONTEND_DOMAIN__ / __API_DOMAIN__ /
  # __TELEPHONY_DOMAIN__ placeholders so each instance gets its own domains.
  sed -e "s/__FRONTEND_DOMAIN__/${DOMAIN}/g" \
      -e "s/__API_DOMAIN__/${API_DOMAIN}/g" \
      -e "s/__TELEPHONY_DOMAIN__/${TELEPHONY_DOMAIN}/g" \
      "$PROJECT_ROOT/infra/nginx/nginx-robocall.conf" > "/etc/nginx/sites-available/${DOMAIN}"
  ln -sf "/etc/nginx/sites-available/${DOMAIN}" "/etc/nginx/sites-enabled/${DOMAIN}"
  rm -f /etc/nginx/sites-enabled/default
  nginx -t
  systemctl restart nginx
  ok "nginx configured for ${DOMAIN}, ${API_DOMAIN}, ${TELEPHONY_DOMAIN} (HTTP only, pre-SSL)"
}

setup_ssl() {
  log "Requesting Let's Encrypt certificates (needs DNS for these domains pointed here already)"
  if certbot --nginx --non-interactive --agree-tos -m "$LETSENCRYPT_EMAIL" --redirect \
       -d "$DOMAIN" -d "$API_DOMAIN" -d "$TELEPHONY_DOMAIN"; then
    ok "SSL certificates installed; nginx now serves HTTPS with auto-redirect"
  else
    echo -e "${RED}SSL setup failed — likely DNS for ${DOMAIN}/${API_DOMAIN}/${TELEPHONY_DOMAIN} isn't pointing at ${SERVER_PUBLIC_IP} yet.${NC}"
    echo "The app is still reachable over plain HTTP. Once DNS propagates, re-run:"
    echo "  sudo certbot --nginx --redirect -d ${DOMAIN} -d ${API_DOMAIN} -d ${TELEPHONY_DOMAIN}"
  fi
}

print_summary() {
  cat > "$CREDENTIALS_FILE" <<EOF
robocall production credentials — generated $(date -u +%Y-%m-%dT%H:%M:%SZ)
Keep this file secret; move the values into a password manager and delete it.

Postgres role 'callbot' password: ${DB_PASSWORD}
robocall_crm admin login:               admin / ${CRM_ADMIN_PASSWORD}
callbot frontend admin login:     admin / ${AUTH_INITIAL_PASSWORD}
Shared telephony worker token:    ${TELEPHONY_TOKEN}
robocall_crm session secret:            ${CRM_SESSION_SECRET}
EOF
  chmod 600 "$CREDENTIALS_FILE"

  echo
  ok "Deployment complete"
  echo "  Frontend:      https://${DOMAIN}"
  echo "  Callbot API:   https://${API_DOMAIN}/api"
  echo "  Telephony API:     https://${TELEPHONY_DOMAIN}/api"
  echo "  Credentials:   ${CREDENTIALS_FILE} (root-only, chmod 600)"
