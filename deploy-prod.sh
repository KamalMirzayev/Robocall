#!/bin/bash
# ============================================================================
# deploy-prod.sh — first-time production install; one instance per customer
# organization, each on its own fresh server with its own domains.
#
# Target: fresh Ubuntu 24.04 server.
# Installs: PostgreSQL 16, Node.js 20, nginx + Let's Encrypt SSL, ffmpeg,
# Asterisk PBX (PJSIP/ARI/AMI), and the three app-layer services
# (robocall-api, robocall-frontend, robocall-telephony) as systemd units —
# matching docs/DEPLOYMENT.md but automated
# end to end for a brand-new box.
#
# Usage (on the target server, as root/sudo):
#   sudo mkdir -p /opt/robocall
#   sudo git clone https://github.com/easgarli/robocall.git /opt/robocall
#   cd /opt/robocall
#   sudo ./deploy-prod.sh
#
# The script prompts for this instance's three domains (frontend, API,
# telephony) and generates per-instance secrets (DB password, Asterisk
# AMI/ARI, worker token). For unattended installs pre-set the variables:
#   FRONTEND_DOMAIN=crm.customer1.robocall.az \
#   API_DOMAIN=api.customer1.robocall.az \
#   TELEPHONY_DOMAIN=telephony.customer1.robocall.az \
#   LETSENCRYPT_EMAIL=ops@robocall.az \
#   sudo -E ./deploy-prod.sh
#
# Before running: point DNS A (and AAAA if you have IPv6) records at this
# server's public IP for the three domains above. SSL issuance (setup_ssl)
# will fail harmlessly if DNS hasn't propagated yet — the app still comes up
# over plain HTTP and you can re-run certbot later.
#
# What this script does with Asterisk, and what it deliberately leaves alone:
#   - Installs the `asterisk` package and copies this repo's infra/asterisk/config/
#     (transports, dialplan contexts, ARI/AMI, modules, RTP range) into
#     /etc/asterisk/ — rewriting pjsip.conf's external_media_address /
#     external_signaling_address to this server's detected public IP, and
#     writing fresh per-instance AMI/ARI secrets into manager.conf/ari.conf
#     (the same values go into apps/telephony/.env).
#   - Does NOT copy infra/asterisk/custom/*.conf: those are marked "Generated by
#     CRM" — the robocall-telephony backend (re)writes them into ASTERISK_CONFIG_DIR
#     whenever an admin clicks Telephony -> "Generate & Reload", and the
#     checked-in copies hold the OLD server's live trunk secrets and
#     extensions. Empty placeholders are seeded instead so Asterisk's
#     #include lines don't fail before anything is configured.
#   - Does NOT open SIP (5060/udp) or RTP (11000-11100/udp) in ufw: this
#     server's real GSM gateway / SIP trunk provider IP isn't known yet
#     (the old infra/asterisk/custom/pjsip_dynamic.conf pointed at a gateway on the
#     previous office LAN, 192.168.38.230, which this VPS can't reach at
#     all). Set ASTERISK_TRUNK_PROVIDER_IP and re-run, or add the ufw rules
#     by hand, once you have the real trunk/gateway IP for this server.
#   - GEMINI_API_KEY / PKS_DB_QUERY_API_KEY: left blank in the generated
#     .env — set via Telephony -> AI API in the web UI, or by editing
#     apps/callbot-backend/.env and restarting robocall-api.
#
# Re-running: mostly safe (guarded steps for user/db/asterisk creation), but
# this script is meant for a first-time install, not routine deploys — use
# ./deploy.sh for pull/build/restart on an already-provisioned server.
# ============================================================================
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

[ "$EUID" -eq 0 ] || { echo "Run as root: sudo ./deploy-prod.sh" >&2; exit 1; }

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVICE_USER="callbot"
NODE_MAJOR=20
ASTERISK_TRUNK_PROVIDER_IP="${ASTERISK_TRUNK_PROVIDER_IP:-}"
LETSENCRYPT_EMAIL="${LETSENCRYPT_EMAIL:-e.asgarli@gmail.com}"
CREDENTIALS_FILE="/root/robocall_credentials_$(date +%Y%m%d%H%M%S).txt"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'
log()  { echo -e "\n${YELLOW}==> $1${NC}"; }
ok()   { echo -e "${GREEN}✓ $1${NC}"; }
gen_secret() { openssl rand -hex 24; }

# ---------------------------------------------------------------------------
# Instance identity: every customer organization gets its own server with its
# own domain set. Prompt on first install; pre-set the variables (or run with
# `FRONTEND_DOMAIN=... API_DOMAIN=... TELEPHONY_DOMAIN=...`) for unattended
# installs. Each var may be exported directly; DOMAIN accepts FRONTEND_DOMAIN.
# ---------------------------------------------------------------------------
DOMAIN="${FRONTEND_DOMAIN:-${DOMAIN:-}}"
if [ -z "$DOMAIN" ]; then
  read -rp "Frontend domain for this instance (e.g. crm.customer1.robocall.az): " DOMAIN
fi
[ -n "$DOMAIN" ] || { echo "Frontend domain is required" >&2; exit 1; }
API_DOMAIN="${API_DOMAIN:-}"
if [ -z "$API_DOMAIN" ]; then
  read -rp "API domain [api.${DOMAIN}]: " API_DOMAIN
  API_DOMAIN="${API_DOMAIN:-api.${DOMAIN}}"
fi
TELEPHONY_DOMAIN="${TELEPHONY_DOMAIN:-}"
if [ -z "$TELEPHONY_DOMAIN" ]; then
  read -rp "Telephony domain [telephony.${DOMAIN}]: " TELEPHONY_DOMAIN
  TELEPHONY_DOMAIN="${TELEPHONY_DOMAIN:-telephony.${DOMAIN}}"
fi
log "Instance domains: frontend=${DOMAIN}, api=${API_DOMAIN}, telephony=${TELEPHONY_DOMAIN}"

# Public IP: auto-detect (curl/ip fallbacks), env override wins, prompt as
# last resort — the previous hardcoded value only matched the original box.
SERVER_PUBLIC_IP="${SERVER_PUBLIC_IP:-}"
if [ -z "$SERVER_PUBLIC_IP" ]; then
  SERVER_PUBLIC_IP="$(curl -fsS --max-time 8 https://ifconfig.me 2>/dev/null \
    || curl -fsS --max-time 8 https://api.ipify.org 2>/dev/null \
    || hostname -I 2>/dev/null | awk '{print $1}' || true)"
fi
if [ -z "$SERVER_PUBLIC_IP" ]; then
  read -rp "Public IP of this server: " SERVER_PUBLIC_IP
fi
[ -n "$SERVER_PUBLIC_IP" ] || { echo "Public IP is required" >&2; exit 1; }

# Fresh per-install Asterisk secrets — shared static credentials across
# customer instances would let one tenant talk to another's Asterisk.
ASTERISK_AMI_SECRET="$(gen_secret)"
ASTERISK_ARI_SECRET="$(gen_secret)"

install_system_packages() {
  # PostgreSQL is deliberately NOT installed here — see ensure_postgres() in
  # setup_postgres(), which detects an already-installed server (e.g. a
  # manually-installed PG17 via the PGDG repo) before falling back to
  # installing one itself, so this script never fights an existing install by
  # pulling in Ubuntu's default PG16 alongside it.
  log "Installing system packages (asterisk, nginx, ffmpeg, certbot, ufw, build tools)"
  apt-get update
  apt-get install -y curl git build-essential ffmpeg nginx \
    asterisk \
    certbot python3-certbot-nginx ufw ca-certificates
  ok "System packages installed"
}

install_node() {
  if command -v node >/dev/null && [ "$(node -v | sed 's/^v//' | cut -d. -f1)" -ge "$NODE_MAJOR" ]; then
    ok "Node.js $(node -v) already installed"
  else
    log "Installing Node.js ${NODE_MAJOR}.x"
    curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash -
    apt-get install -y nodejs
    ok "Node.js $(node -v) installed"
  fi
}

create_service_user() {
  log "Creating service user '$SERVICE_USER'"
  if id -u "$SERVICE_USER" >/dev/null 2>&1; then
    ok "Service user '$SERVICE_USER' already exists"
  else
    # -m/-d gives it a real home dir (needed for npm's cache); useradd -r alone
    # (as docs/DEPLOYMENT.md shows) leaves HOME unset and breaks
    # `npm install` when run as this user below.
    useradd -r -m -d /home/callbot -s /bin/false "$SERVICE_USER"
    ok "Created system user '$SERVICE_USER'"
  fi

  mkdir -p /var/log/robocall/backend /var/log/robocall/frontend /var/log/robocall/telephony
  chown -R "$SERVICE_USER:$SERVICE_USER" /var/log/robocall
  mkdir -p "$PROJECT_ROOT/recordings"
  chown -R "$SERVICE_USER:$SERVICE_USER" "$PROJECT_ROOT"
  ok "Directories and ownership set"
}

install_asterisk() {
  log "Configuring Asterisk PBX"

  # Static base config: transports, dialplan contexts, ARI/AMI, modules, RTP range.
  # Copied as-is except the PJSIP transport's external address and the AMI/ARI
  # secrets, rewritten below for this server/instance — the repo's tracked
  # copies keep placeholder values only.
  install -m 640 -o asterisk -g asterisk "$PROJECT_ROOT/infra/asterisk/config/pjsip.conf" /etc/asterisk/pjsip.conf
  sed -i \
    -e "s/^external_media_address=.*/external_media_address=${SERVER_PUBLIC_IP}/" \
    -e "s/^external_signaling_address=.*/external_signaling_address=${SERVER_PUBLIC_IP}/" \
    /etc/asterisk/pjsip.conf

  for f in manager.conf modules.conf extensions.conf ari.conf rtp.conf http.conf; do
    install -m 640 -o asterisk -g asterisk "$PROJECT_ROOT/infra/asterisk/config/$f" "/etc/asterisk/$f"
  done

  # Per-instance AMI/ARI secrets (generated above; the same values are written
  # into apps/telephony/.env by write_env_files()).
  sed -i "s/^secret=.*/secret=${ASTERISK_AMI_SECRET}/" /etc/asterisk/manager.conf
  sed -i "s/^password=.*/password=${ASTERISK_ARI_SECRET}/" /etc/asterisk/ari.conf

  # Dynamic config dir: (re)written at runtime by the robocall-telephony backend
  # (ASTERISK_CONFIG_DIR) whenever an admin clicks Telephony -> "Generate &
  # Reload". Seed empty placeholders only — see header comment for why we
  # don't copy this repo's infra/asterisk/custom/*.conf here.
  mkdir -p /etc/asterisk/custom
  [ -f /etc/asterisk/custom/pjsip_dynamic.conf ] || : > /etc/asterisk/custom/pjsip_dynamic.conf
  [ -f /etc/asterisk/custom/extensions_dynamic.conf ] || : > /etc/asterisk/custom/extensions_dynamic.conf
  chown -R asterisk:asterisk /etc/asterisk/custom
  chmod 2775 /etc/asterisk/custom
  chmod 664 /etc/asterisk/custom/*.conf

  # robocall-api/robocall-telephony run as $SERVICE_USER with
  # SupplementaryGroups=asterisk (see infra/systemd/*.service) so they can read AMI/ARI
  # and write the dynamic config dir above.
  usermod -aG asterisk "$SERVICE_USER"

  # Logrotate: prevent unbounded Asterisk log growth (messages.log, debug, full, *_log)
  cp "$PROJECT_ROOT/infra/misc/asterisk-logrotate.conf" /etc/logrotate.d/asterisk
  chmod 644 /etc/logrotate.d/asterisk

  systemctl enable --now asterisk
  systemctl restart asterisk
  ok "Asterisk installed, PJSIP transport bound to ${SERVER_PUBLIC_IP}:5060 — SIP accounts/trunks are configured via the web UI"
}

ensure_postgres() {
  # Detect an already-installed, running server first (e.g. this box already
  # has PostgreSQL 17 manually installed via the PGDG repo) rather than
  # blindly apt-installing Ubuntu 24.04's default "postgresql" meta-package
  # (PG16) — that would add a second cluster fighting the first one for
  # port 5432 instead of being used by it.
  if command -v psql >/dev/null 2>&1 && (systemctl list-unit-files 2>/dev/null | grep -q '^postgresql'); then
    systemctl enable --now postgresql
    ok "Found existing PostgreSQL install — using it"
  else
    log "No existing PostgreSQL found — installing PostgreSQL 17 from the PGDG apt repository"
    install -d -m 755 /usr/share/postgresql-common/pgdg
    curl -fsSL https://www.postgresql.org/media/keys/ACCC4CF8.asc \
      | gpg --dearmor -o /usr/share/postgresql-common/pgdg/apt.postgresql.org.gpg
    # shellcheck disable=SC1091
    . /etc/os-release
    echo "deb [signed-by=/usr/share/postgresql-common/pgdg/apt.postgresql.org.gpg] https://apt.postgresql.org/pub/repos/apt ${VERSION_CODENAME}-pgdg main" \
      > /etc/apt/sources.list.d/pgdg.list
    apt-get update
    apt-get install -y postgresql-17 postgresql-contrib-17
    systemctl enable --now postgresql
    ok "PostgreSQL 17 installed"
  fi

  local pg_version
  pg_version="$(sudo -u postgres psql -tAc 'SHOW server_version;' | xargs)"
  local pg_major="${pg_version%%.*}"
  if [ "${pg_major:-0}" -lt 16 ]; then
    echo -e "${RED}Warning: detected PostgreSQL ${pg_version}; this project targets 16+ (pgcrypto's gen_random_uuid(), etc). Consider upgrading.${NC}" >&2
  fi
  ok "Using PostgreSQL ${pg_version}"
}

setup_postgres() {
  log "Configuring PostgreSQL"
  ensure_postgres

  if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='callbot'" | grep -q 1; then
    ok "Postgres role 'callbot' already exists — reusing it"
    if [ -z "${DB_PASSWORD:-}" ]; then
      echo -e "${RED}Role 'callbot' already exists but DB_PASSWORD wasn't provided.${NC}" >&2
      echo "Become root first (sudo -i), then: export DB_PASSWORD=<the existing password> && ./deploy-prod.sh" >&2
      echo "(a plain 'sudo DB_PASSWORD=... ./deploy-prod.sh' won't reliably pass the variable through)" >&2
      echo "Or drop the role for a clean install: sudo -u postgres dropdb callbot && sudo -u postgres dropuser callbot" >&2
      exit 1
    fi
  else
    DB_PASSWORD="$(gen_secret)"
    sudo -u postgres psql -v ON_ERROR_STOP=1 -c "CREATE ROLE callbot WITH LOGIN CREATEDB PASSWORD '${DB_PASSWORD}';"
    ok "Created Postgres role 'callbot'"
  fi

  sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='robocall_callbot'" | grep -q 1 \
    || sudo -u postgres createdb -O callbot robocall_callbot

  log "Applying infra/postgres/init schema (robocall_callbot db, then robocall_crm db)"
  PGPASSWORD="$DB_PASSWORD" psql -h 127.0.0.1 -U callbot -d robocall_callbot -v ON_ERROR_STOP=1 \
    -f "$PROJECT_ROOT/infra/postgres/init/001_schema.sql"
  PGPASSWORD="$DB_PASSWORD" psql -h 127.0.0.1 -U callbot -d robocall_callbot -v ON_ERROR_STOP=1 \
    -f "$PROJECT_ROOT/infra/postgres/init/002_create_robocall_crm_db.sql"

  sudo -u postgres psql -v ON_ERROR_STOP=1 -c "ALTER SYSTEM SET max_connections = 200;" >/dev/null
  systemctl restart postgresql
  ok "PostgreSQL ready: databases 'robocall_callbot' and 'robocall_crm', role 'callbot'"
}

